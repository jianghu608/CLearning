/* 浙工大转专业机考真题 题4 — 空心菱形

题目描述
一个空心的菱形可以是由两个一正一倒的V字相合而成。现在让我们来画个空心菱形吧。

输入
多组输入，每组输入V字的高度n和构成的字符。（5≤n≤30）

输出
输出由给定字符围边的菱形。
注意：每组输出之间有一个空行（第一组前不需要）。

样例
输入：
3 T
5 *

输出：
  T
 TTT
TT TT
TT TT
 TTT
  T

    *
   ***
  ** **
 **   **
**     **
**     **
 **   **
  ** **
   ***
    *

规律分析
以 n=5, ch='*' 为例，菱形共 2n 行：

上半部分（第1~n行）：
  行1:     *          (1个字符)
  行2:    ***         (3个字符，全填充)
  行3:   ** **        (2个* + 空格 + 2个*)
  行4:  **   **       (2个* + 3空格 + 2个*)
  行5: **     **      (2个* + 5空格 + 2个*)

下半部分（第n+1~2n行）：
  与上半部分对称（去掉尖）

每组输出间有一个空行（第一组前不加）。

*/


// 分析：1.先分为上下两部分，用两个索引确定字符数量
//      2.顶端部分第一行只有一个字符，第二行由三个字符构成，其余行边用两个字符构成
//      3.高度为5，可以将特殊情况分出来
//      4.宽度：每次向外移一格，最宽处为第一个空 空格宽：1, 3, 5, ...
#include <stdio.h>

int main(void) {
    // 输入半高度和字符
    int h;
    char sign;
    while(scanf("%d %c", &h, &sign) != EOF) {
        // 第一部分
        // 宽度减小了 h-1 次
        // 第一行
        for (int i = 0; i < h-1; i++) {
            printf(" ");
        }
        printf("%c\n", sign);

        // 第二行
        for (int i = 0; i < h-2; i++) {
            printf(" ");
        }
        printf("%c%c%c\n", sign, sign, sign);

        // 第 3+i 行开始，剩余 h-2 行，开始用循环打印
        int up = h-2; // 从下往上数第 h-2 行
        for (int i = 0; i < h-2; i++) { // 打印 h-2 行
            // 前面的空格，上升一行空一格，0, 1, 2, h-1... j = h-行数
            for (int j = 0; j < up-1; j++) {
                printf(" ");
            }    // 打印 (h+1)-(3+i) 个空格

            // 两个字符
            printf("%c%c", sign, sign);

            // 中间的空格，从小到大，+2，空格数 k = 1+2*i
            for (int k = 0; k < 1+2*i; k++) {
                printf(" ");
            }

            // 两个字符
            printf("%c%c\n", sign, sign);
            up--;
        }

        // 第二部分，反过来计数
        // 打印 h-2 行，变 h-3 次
        int down = h-2;
        for (int i = 0; i < h-2; i++) {
            // 前面的空格，上升一行空一格，0, 1, 2, h-1... j = h-行数
            for (int j = 0; j < i; j++) printf(" ");
            // 两个字符
            printf("%c%c", sign, sign);
            // 中间的空格，从大到小，-2，空格数 k = 2*down-1
            for (int k = 0; k < 1+2*(h-3)-2*i; k++) printf(" ");
            // 两个字符
            printf("%c%c\n", sign, sign);
            down--;
        }

        // 第二行
        for (int i = 0; i < h-2; i++) printf(" ");
        printf("%c%c%c\n", sign, sign, sign);

        // 第一行
        for (int i = 0; i < h-1; i++) {
            printf(" ");
        }
        printf("%c\n", sign);
    }



    return 0;
}
